// fibonacci.c
/*
   Javascript calls a custom C function, "fib".
   In order to call fib, we need to do a little more coding in our html file.
   Essentially, we need to add a function call provided for us in the JS file to our html script.
   There are two such functions: cwrap and ccall, we demonstrate both.
   Compile using the following options,
      emcc fibonacci.c -o fibonacci.js -s WASM=1 -s EXPORTED_FUNCTIONS=_fib -sEXPORTED_RUNTIME_METHODS=ccall,cwrap
  Note the different option for -o, we output only the js file and not an autogenerated html file, we will use a custom html file.
  Also, the underscore before the name of our c function is required.
  Emscripten, during compilation, ignores all functions that do not seem to be used. 
  To avoid this situation we include the EXPORTED options in the compile line as shown above.
  See fibonacci.html for the additional required code.
*/

int fib(int n)
{
    if(n == 0 || n == 1)
        return 1;
    else
        return fib(n - 1) + fib(n - 2);
}

